def test_alembic_upgrade_downgrade_execution(alembic_config, monkeypatch):
    """
    Test running the actual Alembic upgrade and downgrade against a disposable database.
    This ensures the generated migration SQL is completely valid for PostgreSQL.
    """
    test_db_url = "postgresql+psycopg://hawkeye:hawkeye@localhost:5432/hawkeye_test"
    
    # We patch the environment variable so get_settings() returns our test DB
    with patch.dict(os.environ, {"DATABASE_URL": test_db_url}):
        # Need to ensure that Settings picks it up if it's evaluated inside env.py
        # Actually env.py calls get_settings(), which is cached by lru_cache!
        # So we clear the cache for testing.
        from app.core.config import get_settings
        from app.db.models import Base
        from sqlalchemy import create_engine
        get_settings.cache_clear()
        
        # Clean up any dangling schema from crashed tests before upgrading
        eng = create_engine(test_db_url)
        Base.metadata.drop_all(eng)
        eng.dispose()
        
        script = ScriptDirectory.from_config(alembic_config)
        revisions = list(script.walk_revisions())
        assert len(revisions) > 0
        
        # Upgrade to head
        command.upgrade(alembic_config, "head")
        
        # Verify tables exist in test db
        engine = create_engine(test_db_url)
        inspector = inspect(engine)
        tables = inspector.get_table_names()
        assert "processing_sessions" in tables
        assert "evidence" in tables
        
        # Downgrade to base
        command.downgrade(alembic_config, "base")
        
        # Verify tables are removed
        inspector = inspect(engine)
        tables = inspector.get_table_names()
        assert "processing_sessions" not in tables
        assert "evidence" not in tables

